-- y sus tablas de auditoría Envers.
-- ============================================================================

-- Work Authors ---------------------------------------------------------------
CREATE TABLE work_authors (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id      BIGINT       NOT NULL,
    author_id    BIGINT       NOT NULL,
    role         VARCHAR(100),
    enabled      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP(6) WITH TIME ZONE,
    updated_at   TIMESTAMP(6) WITH TIME ZONE,
    created_by   VARCHAR(50),
    updated_by   VARCHAR(50),
    deleted_at   TIMESTAMP(6) WITH TIME ZONE,
    deleted_by   VARCHAR(50),
    CONSTRAINT fk_work_authors_work   FOREIGN KEY (work_id)   REFERENCES works (id),
    CONSTRAINT fk_work_authors_author FOREIGN KEY (author_id) REFERENCES authors (id)
);

-- Edition Authors ------------------------------------------------------------
CREATE TABLE edition_authors (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edition_id   BIGINT       NOT NULL,
    author_id    BIGINT       NOT NULL,
    role         VARCHAR(100),
    enabled      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP(6) WITH TIME ZONE,
    updated_at   TIMESTAMP(6) WITH TIME ZONE,
    created_by   VARCHAR(50),
    updated_by   VARCHAR(50),
    deleted_at   TIMESTAMP(6) WITH TIME ZONE,
    deleted_by   VARCHAR(50),
    CONSTRAINT fk_edition_authors_edition FOREIGN KEY (edition_id) REFERENCES editions (id),
    CONSTRAINT fk_edition_authors_author  FOREIGN KEY (author_id)  REFERENCES authors (id)
);

