-- ============================================================================
-- Tablas de auditoría Envers
-- ============================================================================

CREATE TABLE work_authors_AUD (
    id           BIGINT NOT NULL,
    REV          INTEGER NOT NULL,
    REVTYPE      SMALLINT,
    work_id      BIGINT,
    author_id    BIGINT,
    role         VARCHAR(100),
    enabled      BOOLEAN,
    created_at   TIMESTAMP(6) WITH TIME ZONE,
    updated_at   TIMESTAMP(6) WITH TIME ZONE,
    created_by   VARCHAR(50),
    updated_by   VARCHAR(50),
    deleted_at   TIMESTAMP(6) WITH TIME ZONE,
    deleted_by   VARCHAR(50),
    PRIMARY KEY (id, REV),
    CONSTRAINT fk_work_authors_aud_rev FOREIGN KEY (REV) REFERENCES REVINFO (REV)
);

CREATE TABLE edition_authors_AUD (
    id           BIGINT NOT NULL,
    REV          INTEGER NOT NULL,
    REVTYPE      SMALLINT,
    edition_id   BIGINT,
    author_id    BIGINT,
    role         VARCHAR(100),
    enabled      BOOLEAN,
    created_at   TIMESTAMP(6) WITH TIME ZONE,
    updated_at   TIMESTAMP(6) WITH TIME ZONE,
    created_by   VARCHAR(50),
    updated_by   VARCHAR(50),
    deleted_at   TIMESTAMP(6) WITH TIME ZONE,
    deleted_by   VARCHAR(50),
    PRIMARY KEY (id, REV),
    CONSTRAINT fk_edition_authors_aud_rev FOREIGN KEY (REV) REFERENCES REVINFO (REV)
);
