-- Agregar reservation_id a stock_items para trackear reserva activa
ALTER TABLE stock_items ADD COLUMN reservation_id BIGINT;

-- Tabla de reservaciones
CREATE TABLE reservations (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    VARCHAR(50)  NOT NULL,
    client_id               BIGINT       NOT NULL,
    edition_id              BIGINT       NOT NULL,
    stock_item_id           BIGINT,
    status                  VARCHAR(20)  NOT NULL DEFAULT 'DEPOSIT_PENDING',
    deposit_percentage      INTEGER      NOT NULL DEFAULT 50,
    deposit_amount          DECIMAL(10,2),
    deposit_paid            BOOLEAN      NOT NULL DEFAULT FALSE,
    total_amount            DECIMAL(10,2),
    total_paid              DECIMAL(10,2) DEFAULT 0,
    reservation_date        TIMESTAMP(6) WITH TIME ZONE,
    pickup_deadline         DATE,
    pickup_date             TIMESTAMP(6) WITH TIME ZONE,
    due_date                DATE,
    return_date             TIMESTAMP(6) WITH TIME ZONE,
    late_fee_per_day        DECIMAL(10,2) DEFAULT 10.00,
    late_fee_total          DECIMAL(10,2) DEFAULT 0,
    renewal_count           INTEGER      DEFAULT 0,
    max_renewals            INTEGER      DEFAULT 1,
    notes                   VARCHAR(500),
    enabled                 BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMP(6) WITH TIME ZONE,
    updated_at              TIMESTAMP(6) WITH TIME ZONE,
    created_by              VARCHAR(50),
    updated_by              VARCHAR(50),
    deleted_at              TIMESTAMP(6) WITH TIME ZONE,
    deleted_by              VARCHAR(50),
    CONSTRAINT uk_reservations_code UNIQUE (code),
    CONSTRAINT fk_reservations_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_reservations_edition FOREIGN KEY (edition_id) REFERENCES editions (id),
    CONSTRAINT fk_reservations_stock_item FOREIGN KEY (stock_item_id) REFERENCES stock_items (id)
);

