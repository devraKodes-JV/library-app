-- ============================================================================
-- Envers audit tables (_AUD) for @Audited stock entities.
-- REVINFO table already created in V1 (IAM schema migration).
-- ============================================================================

-- Auditoría de stock_locations
CREATE TABLE stock_locations_AUD (
    id           BIGINT NOT NULL,
    REV          BIGINT NOT NULL,
    REVTYPE      SMALLINT,
    code         VARCHAR(50),
    name         VARCHAR(100),
    description  VARCHAR(500),
    capacity     INTEGER,
    enabled      BOOLEAN,
    created_at   TIMESTAMP(6) WITH TIME ZONE,
    updated_at   TIMESTAMP(6) WITH TIME ZONE,
    created_by   VARCHAR(50),
    updated_by   VARCHAR(50),
    deleted_at   TIMESTAMP(6) WITH TIME ZONE,
    deleted_by   VARCHAR(50),
    PRIMARY KEY (id, REV),
    CONSTRAINT fk_stock_locations_aud_rev FOREIGN KEY (REV) REFERENCES REVINFO (REV)
);

-- Auditoría de stock_items
CREATE TABLE stock_items_AUD (
    id           BIGINT NOT NULL,
    REV          BIGINT NOT NULL,
    REVTYPE      SMALLINT,
    code         VARCHAR(50),
    edition_id   BIGINT,
    location_id  BIGINT,
    state        VARCHAR(20),
    condition    VARCHAR(20),
    enabled      BOOLEAN,
    created_at   TIMESTAMP(6) WITH TIME ZONE,
    updated_at   TIMESTAMP(6) WITH TIME ZONE,
    created_by   VARCHAR(50),
    updated_by   VARCHAR(50),
    deleted_at   TIMESTAMP(6) WITH TIME ZONE,
    deleted_by   VARCHAR(50),
    PRIMARY KEY (id, REV),
    CONSTRAINT fk_stock_items_aud_rev FOREIGN KEY (REV) REFERENCES REVINFO (REV)
);

-- Auditoría de stock_movements
CREATE TABLE stock_movements_AUD (
    id              BIGINT NOT NULL,
    REV             BIGINT NOT NULL,
    REVTYPE         SMALLINT,
    type            VARCHAR(20),
    stock_item_id   BIGINT,
    source_location_id BIGINT,
    target_location_id BIGINT,
    reason          VARCHAR(500),
    created_at      TIMESTAMP(6) WITH TIME ZONE,
    created_by      VARCHAR(50),
    PRIMARY KEY (id, REV),
    CONSTRAINT fk_stock_movements_aud_rev FOREIGN KEY (REV) REFERENCES REVINFO (REV)
);
