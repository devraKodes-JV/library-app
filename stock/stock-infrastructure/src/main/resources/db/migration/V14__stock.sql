-- Stock Locations -----------------------------------------------------------
CREATE TABLE stock_locations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50)  NOT NULL,
    name            VARCHAR(100) NOT NULL,
    description     VARCHAR(500),
    capacity        INTEGER,
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP(6) WITH TIME ZONE,
    updated_at      TIMESTAMP(6) WITH TIME ZONE,
    created_by      VARCHAR(50),
    updated_by      VARCHAR(50),
    deleted_at      TIMESTAMP(6) WITH TIME ZONE,
    deleted_by      VARCHAR(50),
    CONSTRAINT uk_stock_locations_code UNIQUE (code)
);

-- Stock Items ----------------------------------------------------------------
CREATE TABLE stock_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50)  NOT NULL,
    edition_id      BIGINT       NOT NULL,
    location_id     BIGINT       NOT NULL,
    state           VARCHAR(20)  NOT NULL DEFAULT 'AVAILABLE',
    condition       VARCHAR(20)  NOT NULL DEFAULT 'GOOD',
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP(6) WITH TIME ZONE,
    updated_at      TIMESTAMP(6) WITH TIME ZONE,
    created_by      VARCHAR(50),
    updated_by      VARCHAR(50),
    deleted_at      TIMESTAMP(6) WITH TIME ZONE,
    deleted_by      VARCHAR(50),
    CONSTRAINT uk_stock_items_code UNIQUE (code),
    CONSTRAINT fk_stock_items_edition  FOREIGN KEY (edition_id)   REFERENCES editions (id),
    CONSTRAINT fk_stock_items_location FOREIGN KEY (location_id)  REFERENCES stock_locations (id)
);

-- Stock Movements -----------------------------------------------------------
CREATE TABLE stock_movements (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                VARCHAR(20)  NOT NULL,
    stock_item_id       BIGINT       NOT NULL,
    source_location_id  BIGINT,
    target_location_id  BIGINT,
    reason              VARCHAR(500),
    created_at          TIMESTAMP(6) WITH TIME ZONE,
    created_by          VARCHAR(50),
    CONSTRAINT fk_stock_movements_item      FOREIGN KEY (stock_item_id)        REFERENCES stock_items (id),
    CONSTRAINT fk_stock_movements_source    FOREIGN KEY (source_location_id)   REFERENCES stock_locations (id),
    CONSTRAINT fk_stock_movements_target    FOREIGN KEY (target_location_id)   REFERENCES stock_locations (id)
);

